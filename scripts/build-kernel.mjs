// Assembles src/render/kernel.wat (wabt, a dev dependency) into src/render/kernel.js: the bytes as base64, so the
// library ships no .wasm file and no runtime dependency. `node scripts/build-kernel.mjs --check` fails when stale.
import fs from 'node:fs';
import wabtInit from 'wabt';

const dir = new URL('../src/render/', import.meta.url);
const wat = fs.readFileSync(new URL('kernel.wat', dir), 'utf8');
const wabt = await wabtInit();
const mod = wabt.parseWat('kernel.wat', wat, { simd: true, bulk_memory: true });
mod.validate();
const { buffer } = mod.toBinary({});
const out = `// Generated by scripts/build-kernel.mjs from kernel.wat. Do not edit.
export const KERNEL_BASE64 =
  '${Buffer.from(buffer).toString('base64')}';
`;
const file = new URL('kernel.js', dir);
if (process.argv.includes('--check')) {
  if (fs.readFileSync(file, 'utf8') !== out)
    throw new Error('src/render/kernel.js is stale: node scripts/build-kernel.mjs');
} else fs.writeFileSync(file, out);
console.log('kernel', buffer.length, 'bytes');
